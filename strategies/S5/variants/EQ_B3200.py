"""S5: adaptive, volatility-aware, diversified allocator over a compact per-product market maker.

Two layers, each O(1) per product per tick:

1. Engine (per product): quote at the touch around a fair value with an inventory-skewed size, take liquidity only
   when the book is through a structural fair value (AMETHYST anchor, PINK pearl-sum plug, TOFFEE OU anchor).
   The engine exposes one knob, the inventory cap Q_i (lots), which bounds the position and scales the target lean.
2. Allocator: a portfolio risk budget sum_i Q_i * sigma_i(t) <= B shared by all products. A rule (EQ, A1, A2, A3)
   turns live estimates of sigma_i(t) and mu_i(t) into risk shares w_i, and Q_i = w_i * B / sigma_i(t),
   water-filled against the position limits. size_multiplier(product) = Q_i / limit_i.

Variants differ only in the CONFIG block (generated by make_variants.py).
"""

import json
import math

from datamodel import Order, TradingState

# ---- CONFIG (variants override this block) ----
CONFIG = {
    "rule": "EQ",
    "budget": 3200,
    "half_life": 1000.0,
    "share_step": 0.002
}
# ---- END CONFIG ----

LIMITS = {
    "AMETHYST": 50, "TOFFEE_CAKE": 50, "PAPER_LANTERNS": 50, "JELLY": 50, "PEANUT_BUTTER": 50,
    "DRAGONFRUIT": 40, "GRANADILLA": 40, "MANGOSTEEN": 40, "FRUIT_BASKET": 40, "LYCHEE": 200,
    "WHITE_PEARLS": 20, "BLACK_PEARLS": 20, "GOLDEN_PEARLS": 20, "PINK_PEARLS": 20, "BLUE_PEARLS": 20,
}
PRODUCTS = tuple(LIMITS)
PEARLS = ("WHITE_PEARLS", "BLACK_PEARLS", "GOLDEN_PEARLS", "PINK_PEARLS", "BLUE_PEARLS")
MEAN_REVERTING = ("AMETHYST", "TOFFEE_CAKE", "PAPER_LANTERNS", "PINK_PEARLS")

# Static long-run tick sigma per product (params.json process sigma; jump products from EDA jump stats).
# EQ uses these; the adaptive rules use them only as the EWMA prior.
SIGMA_EDA = {
    "AMETHYST": 0.1, "TOFFEE_CAKE": 2.24, "PAPER_LANTERNS": 0.45, "JELLY": 3.14, "PEANUT_BUTTER": 4.82,
    "DRAGONFRUIT": 2.05, "GRANADILLA": 1.63, "MANGOSTEEN": 2.34, "FRUIT_BASKET": 8.0, "LYCHEE": 1.19,
    "WHITE_PEARLS": 2.28, "BLACK_PEARLS": 2.31, "GOLDEN_PEARLS": 0.3, "PINK_PEARLS": 0.84, "BLUE_PEARLS": 1.42,
}
SIGMA_FLOOR = 0.1  # AMETHYST's true diffusion is zero; floor keeps Q = B * w / sigma finite (then limit-clipped)
# Noise-taker print rate per tick and mean lots per print (params.json flow), the Beta-Bernoulli prior mean.
PRINT_RATE = {
    "AMETHYST": 0.0143, "TOFFEE_CAKE": 0.0068, "PAPER_LANTERNS": 0.0105, "JELLY": 0.0064, "PEANUT_BUTTER": 0.0073,
    "DRAGONFRUIT": 0.0019, "GRANADILLA": 0.0025, "MANGOSTEEN": 0.0019, "FRUIT_BASKET": 0.0016, "LYCHEE": 0.0058,
    "WHITE_PEARLS": 0.0065, "BLACK_PEARLS": 0.0055, "GOLDEN_PEARLS": 0.0059, "PINK_PEARLS": 0.0061,
    "BLUE_PEARLS": 0.0057,
}
LOTS_PER_PRINT = {"TOFFEE_CAKE": 3.6, "FRUIT_BASKET": 2.2}  # default 2.2 (uniform 1..3/1..4 sizes)
# L1 half spread (params.json book layer 0 half_width): the prior for the per-lot markout.
HALF_SPREAD = {
    "AMETHYST": 1.0, "TOFFEE_CAKE": 6.5, "PAPER_LANTERNS": 1.5, "JELLY": 4.5, "PEANUT_BUTTER": 2.5,
    "DRAGONFRUIT": 1.5, "GRANADILLA": 1.5, "MANGOSTEEN": 1.5, "FRUIT_BASKET": 2.5, "LYCHEE": 1.5,
    "WHITE_PEARLS": 1.5, "BLACK_PEARLS": 3.5, "GOLDEN_PEARLS": 1.0, "PINK_PEARLS": 1.5, "BLUE_PEARLS": 2.5,
}
QUOTE_SIZE = {"TOFFEE_CAKE": 6}  # max noise-taker size (params.json); default 4. Takers always hit the touch.
PRIOR_TICKS = 500.0  # Beta prior strength for the fill rate, in ticks of pseudo-observations

AMETHYST_ANCHOR = 10000.0
ANCHOR_TOL = 3.0  # real days never left 9,999.5-10,000.5; a long EWMA 3 away means the anchor broke
PAPER_ALPHA = 2.0 / (5 + 1)  # EDA: EWMA span 5 has 16% lower RMSE than raw mid
TOFFEE_ANCHOR0 = 5003.3  # params.json OU mean
TOFFEE_KAPPA = 0.0046  # params.json OU mean-reversion rate per tick (half-life ~150 ticks)
TOFFEE_SD = 2.24 / math.sqrt(2 * 0.0046)  # stationary sd of the OU deviation, ~23
TOFFEE_HORIZON = 100.0  # holding horizon for the OU fair value (~2/3 of the half-life)
TOFFEE_ANCHOR_ALPHA = 2.0 / (3000 + 1)  # slow anchor estimate, survives mean-reversion-decay drift
TOFFEE_FAST_ALPHA = 2.0 / (3 + 1)  # EDA: EWMA span ~3 for the current level
PEARL_TOTAL0 = 50000.0
PINK_SLOPE = 1.105  # params.json: a PINK jump is -1.105 x the sum deviation
PINK_HAZARD = ((5.0, 0.00026), (10.0, 0.0097), (1e9, 0.064))  # P(jump per tick | |dev| < edge)
PINK_HORIZON = 20.0  # EDA's 20-tick move statistic
PINK_JUMP = 4.0  # a PINK mid move > 4 (8 x its 0.5 flat noise sd) is a plug jump
PINK_TOTAL_ALPHA = 0.2  # post-jump sum is a direct reading of the total (residual sd 1.3)
GOLDEN_ALPHA = 2.0 / (200 + 1)  # EDA: plateau = long EWMA
GOLDEN_STEP = 5.0  # plateau noise is +/-0.5; steps are 50-100
GOLDEN_RAMP = 85  # params.json step ramp length (ticks)
TAKE_EDGE = 1.0  # take only when the book is at least 1 tick through fair value
SHOCK_SIGMAS = 8.0  # a single-tick move this many long-run sigmas pauses the product
SHOCK_PAUSE = 20  # ticks
SHOCK_EXEMPT = ("PINK_PEARLS", "GOLDEN_PEARLS")  # their jumps are the signal / handled by the step logic
MARKOUT_MEMORY_LOTS = 200.0  # EWMA memory of the per-lot markout, in filled lots


def _ewma_alpha(half_life):
    return 1.0 - 0.5 ** (1.0 / max(half_life, 1.0))


def _clip(x, lo, hi):
    return lo if x < lo else hi if x > hi else x


def _new_product_state(product, mid):
    return {
        "m": mid,  # last mid
        "d": 0.0,  # last mid change
        "g0": SIGMA_EDA[product] ** 2,  # EWMA E[dm^2]
        "g1": 0.0,  # EWMA E[dm_t dm_{t-1}]
        "f": mid,  # smoothed fair value / plateau
        "a": PRINT_RATE[product] * PRIOR_TICKS,  # Beta alpha (ticks with a print)
        "b": (1 - PRINT_RATE[product]) * PRIOR_TICKS,  # Beta beta
        "k": HALF_SPREAD[product],  # EWMA markout per lot
        "w": 1.0 / len(PRODUCTS),  # current risk share
        "p": 0,  # pause / ramp timer
    }


class Allocator:
    """Risk-budget allocator. Online inputs per product: sigma_i(t) and mu_i(t). Output: inventory caps Q_i."""

    def __init__(self, config):
        self.rule = config["rule"]
        self.budget = config["budget"]
        self.alpha = _ewma_alpha(config["half_life"])
        self.share_step = config["share_step"]

    def update_sigma(self, st, dm):
        a = self.alpha
        st["g0"] += a * (dm * dm - st["g0"])
        st["g1"] += a * (dm * st["d"] - st["g1"])
        st["d"] = dm

    def sigma(self, product, st):
        # Noise + random walk makes dm an MA(1): long-run variance = gamma0 + 2 gamma1 (strips quote noise).
        if self.rule == "EQ":
            return SIGMA_EDA[product]
        return math.sqrt(max(st["g0"] + 2.0 * st["g1"], SIGMA_FLOOR ** 2))

    def update_edge(self, st, printed, markout_sum, lots):
        # Discounted Beta-Bernoulli: P(a taker print this tick), effective memory 1 / alpha ticks.
        keep = 1.0 - self.alpha
        st["a"] = keep * st["a"] + (1.0 if printed else 0.0)
        st["b"] = keep * st["b"] + (0.0 if printed else 1.0)
        if lots > 0:
            weight = 1.0 - (1.0 - 1.0 / MARKOUT_MEMORY_LOTS) ** lots
            st["k"] += weight * (markout_sum / lots - st["k"])

    def mu(self, product, st, signal_edge):
        rate = st["a"] / (st["a"] + st["b"])
        return max(rate * LOTS_PER_PRINT.get(product, 2.2) * st["k"], 0.0) + signal_edge

    def raw_scores(self, sig, mus):
        rule = self.rule
        if rule == "EQ":
            return {p: 1.0 for p in sig}
        if rule == "A1":
            return dict(sig)
        if rule == "A1MR":
            mean_sig = {p: SIGMA_EDA[p] for p in sig}
            return {p: (sig[p] / mean_sig[p] if p in MEAN_REVERTING else 1.0) for p in sig}
        if rule == "A3":
            return {p: 1.0 / sig[p] for p in sig}
        # A2: fractional Kelly. Kelly position q = mu / sigma^2, so its risk share q * sigma = mu / sigma.
        return {p: mus[p] / sig[p] for p in sig}

    def caps(self, states, sig, mus):
        scores = self.raw_scores(sig, mus)
        total = sum(scores.values()) or 1.0
        target = {p: s / total for p, s in scores.items()}
        # Water-fill: a product capped at its position limit returns its unused budget to the others.
        caps = {}
        free = set(target)
        budget = self.budget
        for _ in range(4):
            share_sum = sum(target[p] for p in free) or 1.0
            clipped = [p for p in free if budget * target[p] / share_sum / sig[p] >= LIMITS[p]]
            if not clipped:
                break
            for p in clipped:
                caps[p] = float(LIMITS[p])
                budget -= LIMITS[p] * sig[p]
                free.discard(p)
            budget = max(budget, 0.0)
        share_sum = sum(target[p] for p in free) or 1.0
        for p in free:
            caps[p] = budget * target[p] / share_sum / sig[p]
        # Anti-whipsaw: the realised share (cap * sigma / B) moves at most share_step per tick.
        out = {}
        for p, cap in caps.items():
            st = states[p]
            want = cap * sig[p] / self.budget
            w = st["w"] + _clip(want - st["w"], -self.share_step, self.share_step)
            st["w"] = w
            out[p] = _clip(w * self.budget / sig[p], 0.0, float(LIMITS[p]))
        return out


class Trader:
    def __init__(self):
        self.allocator = Allocator(CONFIG)

    def size_multiplier(self, product, cap):
        return cap / LIMITS[product]

    # ---------- state ----------
    @staticmethod
    def _load(trader_data):
        if not trader_data:
            return {}
        try:
            data = json.loads(trader_data)
            return data if isinstance(data, dict) else {}
        except (ValueError, TypeError):
            return {}

    # ---------- fair values and structural signals ----------
    def _fair(self, product, st, mid, mids, g):
        """Return (fair, target_fraction in [-1, 1], signal edge per lot per tick)."""
        if product == "AMETHYST":
            st["f"] += 0.01 * (mid - st["f"])
            fair = AMETHYST_ANCHOR if abs(st["f"] - AMETHYST_ANCHOR) < ANCHOR_TOL else st["f"]
            return fair, 0.0, 0.0
        if product == "PAPER_LANTERNS":
            st["f"] += PAPER_ALPHA * (mid - st["f"])
            return st["f"], 0.0, 0.0
        if product == "TOFFEE_CAKE":
            st["f"] += TOFFEE_FAST_ALPHA * (mid - st["f"])
            anchor = g.setdefault("ta", TOFFEE_ANCHOR0)
            anchor += TOFFEE_ANCHOR_ALPHA * (mid - anchor)
            g["ta"] = anchor
            dev = st["f"] - anchor
            fair = anchor + dev * math.exp(-TOFFEE_KAPPA * TOFFEE_HORIZON)
            return fair, _clip(-dev / TOFFEE_SD, -1.0, 1.0), TOFFEE_KAPPA * abs(dev)
        if product == "GOLDEN_PEARLS":
            if abs(mid - st["f"]) > GOLDEN_STEP:
                st["p"] = GOLDEN_RAMP if mid < st["f"] else -GOLDEN_RAMP
                st["f"] = mid
            else:
                st["f"] += GOLDEN_ALPHA * (mid - st["f"])
            return (mid if st["p"] else st["f"]), 0.0, 0.0
        if product == "PINK_PEARLS" and all(p in mids for p in PEARLS):
            total = g.setdefault("pt", PEARL_TOTAL0)
            dev = sum(mids[p] for p in PEARLS) - total
            if abs(mid - st["m"]) > PINK_JUMP:
                g["pt"] = total + PINK_TOTAL_ALPHA * dev
            hazard = next(h for edge, h in PINK_HAZARD if abs(dev) < edge)
            p_jump = 1.0 - (1.0 - hazard) ** PINK_HORIZON
            move = -PINK_SLOPE * dev * p_jump
            target = _clip(move / (2.0 * HALF_SPREAD[product]), -1.0, 1.0)
            return mid + move, target, hazard * PINK_SLOPE * abs(dev)
        return mid, 0.0, 0.0

    # ---------- orders ----------
    @staticmethod
    def _orders(product, depth, pos, fair, cap, target_frac, paused):
        limit = LIMITS[product]
        best_bid, best_ask = max(depth.buy_orders), min(depth.sell_orders)
        cap_i = int(cap)
        target = int(round(target_frac * cap_i))
        orders = []
        bought = sold = 0
        # Take liquidity through fair value: up to the cap when there is no lean (AMETHYST anchor), else up to
        # the signal's target position (TOFFEE OU, PINK plug).
        upper = cap_i if target_frac == 0 else max(target, 0)
        lower = -cap_i if target_frac == 0 else min(target, 0)
        for price in sorted(depth.sell_orders):
            room = min(abs(depth.sell_orders[price]), limit - pos - bought, upper - pos - bought)
            if price > fair - TAKE_EDGE or room <= 0:
                break
            orders.append(Order(product, price, room))
            bought += room
        for price in sorted(depth.buy_orders, reverse=True):
            room = min(depth.buy_orders[price], limit + pos - sold, pos - sold - lower)
            if price < fair + TAKE_EDGE or room <= 0:
                break
            orders.append(Order(product, price, -room))
            sold += room
        if paused:
            return orders
        # Passive quotes at the touch (takers always hit the touch, so improving only gives away edge).
        size = QUOTE_SIZE.get(product, 4)
        dev = pos - target
        scale = max(cap_i, 1)
        buy_size = int(round(size * _clip(1.0 - dev / scale, 0.0, 1.0)))
        sell_size = int(round(size * _clip(1.0 + dev / scale, 0.0, 1.0)))
        buy_size = min(buy_size, cap_i - pos - bought, limit - pos - bought)
        sell_size = min(sell_size, cap_i + pos - sold, limit + pos - sold)
        if buy_size > 0 and best_bid < fair and best_bid < best_ask:
            orders.append(Order(product, best_bid, buy_size))
        if sell_size > 0 and best_ask > fair and best_ask > best_bid:
            orders.append(Order(product, best_ask, -sell_size))
        return orders

    def run(self, state: TradingState):
        data = self._load(state.traderData)
        states = data.get("s", {})
        g = data.get("g", {})
        alloc = self.allocator
        books = {}
        mids = {}
        for product in PRODUCTS:
            depth = state.order_depths.get(product)
            if depth is None or not depth.buy_orders or not depth.sell_orders:
                continue
            books[product] = depth
            mids[product] = (max(depth.buy_orders) + min(depth.sell_orders)) / 2.0

        fairs, targets, sig, mus = {}, {}, {}, {}
        for product, mid in mids.items():
            st = states.get(product)
            if st is None:
                st = _new_product_state(product, mid)
                states[product] = st
            dm = mid - st["m"]
            # Markout of last tick's fills against this tick's mid, per lot.
            fills = state.own_trades.get(product, []) if state.own_trades else []
            mark, lots = 0.0, 0
            for t in fills:
                sign = 1 if t.buyer == "SUBMISSION" else -1
                mark += sign * (mid - t.price) * abs(t.quantity)
                lots += abs(t.quantity)
            printed = bool(state.market_trades.get(product)) or lots > 0
            alloc.update_edge(st, printed, mark, lots)
            fair, target, signal = self._fair(product, st, mid, mids, g)
            if product not in SHOCK_EXEMPT and abs(dm) > SHOCK_SIGMAS * max(SIGMA_EDA[product], 1.0):
                st["p"] = SHOCK_PAUSE
            alloc.update_sigma(st, dm)
            st["m"] = mid
            fairs[product], targets[product] = fair, target
            sig[product] = alloc.sigma(product, st)
            mus[product] = alloc.mu(product, st, signal)

        caps = alloc.caps(states, sig, mus) if sig else {}
        orders = {}
        for product in fairs:
            st = states[product]
            paused = st["p"] != 0
            if st["p"] > 0:
                st["p"] -= 1
            elif st["p"] < 0:
                st["p"] += 1
            pos = state.position.get(product, 0)
            out = self._orders(product, books[product], pos, fairs[product], caps[product], targets[product], paused)
            if out:
                orders[product] = out
        for st in states.values():
            for key in ("g0", "g1", "f", "a", "b", "k", "w", "d", "m"):
                st[key] = round(st[key], 5)
        trader_data = json.dumps({"s": states, "g": g}, separators=(",", ":"))
        return orders, 0, trader_data
