"""S5: adaptive, volatility-aware, diversified allocator over per-product sub-strategies.

Layers, each O(sub-strategies x products) per tick:

1. Sub-strategies (one instance serves every product it trades). Each has
   intent(ctx, product, mem, q, cap, center) -> list[(price, signed_qty)], edge(...) and variance(...):
   - MarketMaker: quotes at the touch around a fair value with an inventory-skewed size (all 15 products).
   - PinkLean: takes PINK_PEARLS in the direction that restores the five-pearl sum (plug hazard model).
   - ToffeeLean: leans TOFFEE_CAKE against its deviation from the online OU anchor.
2. Allocator.allocate(entries) takes a list of (sub, product, edge, variance) and returns each entry's slice of
   lots. The slices share each product's position limit and a portfolio risk budget sum Q * sigma <= B.
   The rule (EQ, A1, A2, A3, A1MR) sets the risk shares; anti-whipsaw caps each share's change per tick.
3. Trader.run nets all intents per product (a lean's buy against the maker's ask cancels) and clips to the limit.

Variants differ only in the CONFIG block (generated by make_variants.py).
"""

import json
import math

from datamodel import Order, TradingState

# ---- CONFIG (variants override this block) ----
CONFIG = {
    "rule": "A2",
    "budget": 800.0,
    "half_life": 1000.0,
    "share_step": 0.002
}
# ---- END CONFIG ----

LIMITS = {
    "AMETHYST": 50, "TOFFEE_CAKE": 50, "PAPER_LANTERNS": 50, "JELLY": 50, "PEANUT_BUTTER": 50,
    "DRAGONFRUIT": 40, "GRANADILLA": 40, "MANGOSTEEN": 40, "FRUIT_BASKET": 40, "LYCHEE": 200,
    "WHITE_PEARLS": 20, "BLACK_PEARLS": 20, "GOLDEN_PEARLS": 20, "PINK_PEARLS": 20, "BLUE_PEARLS": 20,
}
PRODUCTS = tuple(LIMITS)
PEARLS = ("WHITE_PEARLS", "BLACK_PEARLS", "GOLDEN_PEARLS", "PINK_PEARLS", "BLUE_PEARLS")
MEAN_REVERTING = ("AMETHYST", "TOFFEE_CAKE", "PAPER_LANTERNS", "PINK_PEARLS")

# Static long-run tick sigma per product (params.json process sigma; PINK from its jump rate x size; GOLDEN and
# AMETHYST near zero between steps). EQ uses these; the adaptive rules use them as the EWMA prior.
SIGMA_EDA = {
    "AMETHYST": 0.1, "TOFFEE_CAKE": 2.24, "PAPER_LANTERNS": 0.45, "JELLY": 3.14, "PEANUT_BUTTER": 4.82,
    "DRAGONFRUIT": 2.05, "GRANADILLA": 1.63, "MANGOSTEEN": 2.34, "FRUIT_BASKET": 8.0, "LYCHEE": 1.19,
    "WHITE_PEARLS": 2.28, "BLACK_PEARLS": 2.31, "GOLDEN_PEARLS": 0.3, "PINK_PEARLS": 0.84, "BLUE_PEARLS": 1.42,
}
SIGMA_FLOOR = 0.1  # AMETHYST's true diffusion is zero; the floor keeps Q = B * w / sigma finite (then clipped)
# Noise-taker print rate per tick (params.json flow rate x cluster mean): the Beta-Bernoulli prior mean.
PRINT_RATE = {
    "AMETHYST": 0.0143, "TOFFEE_CAKE": 0.0068, "PAPER_LANTERNS": 0.0105, "JELLY": 0.0064, "PEANUT_BUTTER": 0.0073,
    "DRAGONFRUIT": 0.0019, "GRANADILLA": 0.0025, "MANGOSTEEN": 0.0019, "FRUIT_BASKET": 0.0016, "LYCHEE": 0.0058,
    "WHITE_PEARLS": 0.0065, "BLACK_PEARLS": 0.0055, "GOLDEN_PEARLS": 0.0059, "PINK_PEARLS": 0.0061,
    "BLUE_PEARLS": 0.0057,
}
LOTS_PER_PRINT = {"TOFFEE_CAKE": 3.6}  # mean of the uniform taker size (params.json); default 2.2
# L1 half spread (params.json book layer 0 half_width): the prior for the per-lot markout.
HALF_SPREAD = {
    "AMETHYST": 1.0, "TOFFEE_CAKE": 6.5, "PAPER_LANTERNS": 1.5, "JELLY": 4.5, "PEANUT_BUTTER": 2.5,
    "DRAGONFRUIT": 1.5, "GRANADILLA": 1.5, "MANGOSTEEN": 1.5, "FRUIT_BASKET": 2.5, "LYCHEE": 1.5,
    "WHITE_PEARLS": 1.5, "BLACK_PEARLS": 3.5, "GOLDEN_PEARLS": 1.0, "PINK_PEARLS": 1.5, "BLUE_PEARLS": 2.5,
}
QUOTE_SIZE = {"TOFFEE_CAKE": 6}  # max noise-taker size (params.json); default 4. Takers always hit the touch.
PRIOR_TICKS = 500.0  # Beta prior strength for the print rate, in ticks of pseudo-observations
MARKOUT_MEMORY_LOTS = 200.0  # EWMA memory of the per-lot markout, in filled lots

AMETHYST_ANCHOR = 10000.0
ANCHOR_TOL = 3.0  # real days never left 9,999.5-10,000.5; a long EWMA 3 away means the anchor broke
AMETHYST_ALPHA = 0.01  # ~100-tick EWMA used only by the anchor-break kill switch
PAPER_ALPHA = 2.0 / (5 + 1)  # EDA: EWMA span 5 has 16% lower RMSE than raw mid
TOFFEE_ANCHOR0 = 5003.3  # params.json OU mean
TOFFEE_KAPPA = 0.0046  # params.json OU mean-reversion rate per tick (half-life ~150 ticks)
TOFFEE_SD = 2.24 / math.sqrt(2 * 0.0046)  # stationary sd of the OU deviation, ~23
TOFFEE_HORIZON = 100.0  # holding horizon for the OU fair value (~2/3 of the half-life)
TOFFEE_ANCHOR_ALPHA = 2.0 / (3000 + 1)  # slow anchor estimate, survives mean-reversion-decay drift
TOFFEE_FAST_ALPHA = 2.0 / (3 + 1)  # EDA: EWMA span ~3 for the current level
PEARL_TOTAL0 = 50000.0
PINK_SLOPE = 1.105  # params.json: a PINK jump is -1.105 x the sum deviation
PINK_HAZARD = ((5.0, 0.00026), (10.0, 0.0097), (1e9, 0.064))  # P(jump per tick | |dev| below edge), params.json
PINK_HORIZON = 20.0  # EDA's 20-tick move statistic
PINK_JUMP = 4.0  # a PINK mid move > 4 (8 x its 0.5 flat noise sd) is a plug jump
PINK_TOTAL_ALPHA = 0.2  # the post-jump sum is a direct reading of the total (residual sd 1.3)
GOLDEN_ALPHA = 2.0 / (200 + 1)  # EDA: plateau = long EWMA
GOLDEN_STEP = 5.0  # plateau noise is +/-0.5; steps are 50-100
GOLDEN_RAMP = 85  # params.json step ramp length (ticks)
TAKE_EDGE = 1.0  # take only when the book is at least 1 tick through fair value
SHOCK_SIGMAS = 8.0  # a single-tick move this many long-run sigmas pauses the product's passive quotes
SHOCK_PAUSE = 20  # ticks
CLIP_FAIR = ("PAPER_LANTERNS", "GOLDEN_PEARLS")  # smoothed fairs kept inside the touch (black-swan-squeeze fix)
SHOCK_EXEMPT = ("PINK_PEARLS", "GOLDEN_PEARLS")  # their jumps are the signal / handled by the step logic


def _ewma_alpha(half_life):
    return 1.0 - 0.5 ** (1.0 / max(half_life, 1.0))


def _clip(x, lo, hi):
    return lo if x < lo else hi if x > hi else x


class Context:
    """Per-tick view shared by the sub-strategies: books, mids, fair values and per-product stats."""

    def __init__(self, state, mem, alpha):
        self.state = state
        self.alpha = alpha
        self.stats = mem.setdefault("s", {})
        self.glob = mem.setdefault("g", {})
        self.books, self.mids = {}, {}
        for product in PRODUCTS:
            depth = state.order_depths.get(product)
            if depth is None or not depth.buy_orders or not depth.sell_orders:
                continue
            self.books[product] = depth
            self.mids[product] = (max(depth.buy_orders) + min(depth.sell_orders)) / 2.0
        self.fair = {}
        for product, mid in self.mids.items():
            self._update_stats(product, mid)

    def _update_stats(self, product, mid):
        st = self.stats.get(product)
        if st is None:
            st = {"m": mid, "d": 0.0, "g0": SIGMA_EDA[product] ** 2, "g1": 0.0, "f": mid, "p": 0}
            self.stats[product] = st
        dm = mid - st["m"]
        if product not in SHOCK_EXEMPT and abs(dm) > SHOCK_SIGMAS * max(SIGMA_EDA[product], 1.0):
            st["p"] = SHOCK_PAUSE
        elif st["p"] > 0:
            st["p"] -= 1
        a = self.alpha
        st["g0"] += a * (dm * dm - st["g0"])
        st["g1"] += a * (dm * st["d"] - st["g1"])
        st["d"] = dm
        fair = self._fair(product, st, mid)
        if product in CLIP_FAIR:  # a lagging smoother outside the touch would quote one side only into a trend
            depth = self.books[product]
            fair = _clip(fair, max(depth.buy_orders) + 0.5, min(depth.sell_orders) - 0.5)
        self.fair[product] = fair
        st["m"] = mid

    def _fair(self, product, st, mid):
        if product == "AMETHYST":
            st["f"] += AMETHYST_ALPHA * (mid - st["f"])
            return AMETHYST_ANCHOR if abs(st["f"] - AMETHYST_ANCHOR) < ANCHOR_TOL else st["f"]
        if product == "PAPER_LANTERNS":
            st["f"] += PAPER_ALPHA * (mid - st["f"])
            return st["f"]
        if product == "TOFFEE_CAKE":
            st["f"] += TOFFEE_FAST_ALPHA * (mid - st["f"])
            anchor = self.glob.get("ta", TOFFEE_ANCHOR0)
            anchor += TOFFEE_ANCHOR_ALPHA * (mid - anchor)
            self.glob["ta"] = anchor
            self.glob["td"] = st["f"] - anchor
            return anchor + (st["f"] - anchor) * math.exp(-TOFFEE_KAPPA * TOFFEE_HORIZON)
        if product == "GOLDEN_PEARLS":
            if abs(mid - st["f"]) > GOLDEN_STEP:
                st["p"] = GOLDEN_RAMP  # pause passive quoting through the step's ramp
                st["f"] = mid
            else:
                st["f"] += GOLDEN_ALPHA * (mid - st["f"])
                if st["p"] > 0:
                    st["p"] -= 1
            return mid if st["p"] else st["f"]
        if product == "PINK_PEARLS" and all(p in self.mids for p in PEARLS):
            total = self.glob.get("pt", PEARL_TOTAL0)
            dev = sum(self.mids[p] for p in PEARLS) - total
            if abs(mid - st["m"]) > PINK_JUMP:  # post-jump sum: a direct reading of the (possibly shifted) total
                self.glob["pt"] = total + PINK_TOTAL_ALPHA * dev
            self.glob["pd"] = dev
            hazard = next(h for edge, h in PINK_HAZARD if abs(dev) < edge)
            return mid - PINK_SLOPE * dev * (1.0 - (1.0 - hazard) ** PINK_HORIZON)  # E[PINK in 20 ticks]
        return mid

    def sigma(self, product):
        """Long-run tick sigma. Noise + random walk makes dm an MA(1), so gamma0 + 2 gamma1 strips quote noise."""
        st = self.stats[product]
        return math.sqrt(max(st["g0"] + 2.0 * st["g1"], SIGMA_FLOOR ** 2))

    def paused(self, product):
        return self.stats[product]["p"] > 0


def _take(product, depth, fair, q, lo, hi):
    """Orders that take the book through fair value, keeping the position inside [lo, hi]."""
    orders, bought, sold = [], 0, 0
    for price in sorted(depth.sell_orders):
        room = min(abs(depth.sell_orders[price]), hi - q - bought)
        if price > fair - TAKE_EDGE or room <= 0:
            break
        orders.append((price, room))
        bought += room
    for price in sorted(depth.buy_orders, reverse=True):
        room = min(depth.buy_orders[price], q - sold - lo)
        if price < fair + TAKE_EDGE or room <= 0:
            break
        orders.append((price, -room))
        sold += room
    return orders


class MarketMaker:
    """Touch quotes around the product's fair value, sizes skewed toward `center`; takes through structural fair
    values (AMETHYST anchor). Edge per lot-tick = Beta-Bernoulli print rate x lots per print x EWMA markout."""

    name = "mm"
    products = PRODUCTS

    def intent(self, ctx, product, mem, q, cap, center=0):
        depth, fair = ctx.books[product], ctx.fair[product]
        cap = int(cap)
        lo, hi = center - cap, center + cap
        orders = _take(product, depth, fair, q, lo, hi) if product == "AMETHYST" else []
        if ctx.paused(product):
            return orders
        bought = sum(x for _, x in orders if x > 0)
        sold = -sum(x for _, x in orders if x < 0)
        size = QUOTE_SIZE.get(product, 4)
        dev = (q - center) / max(cap, 1)
        buy = min(int(round(size * _clip(1.0 - dev, 0.0, 1.0))), hi - q - bought)
        sell = min(int(round(size * _clip(1.0 + dev, 0.0, 1.0))), q - sold - lo)
        best_bid, best_ask = max(depth.buy_orders), min(depth.sell_orders)
        if buy > 0 and best_bid < fair:
            orders.append((best_bid, buy))
        if sell > 0 and best_ask > fair:
            orders.append((best_ask, -sell))
        return orders

    def learn(self, ctx, product, mem, alpha):
        st = mem.get(product)
        if st is None:
            st = {"a": PRINT_RATE[product] * PRIOR_TICKS, "b": (1 - PRINT_RATE[product]) * PRIOR_TICKS,
                  "k": HALF_SPREAD[product]}
            mem[product] = st
        state, mid = ctx.state, ctx.mids[product]
        mark, lots = 0.0, 0
        for t in (state.own_trades or {}).get(product, []):
            sign = 1 if t.buyer == "SUBMISSION" else -1
            mark += sign * (mid - t.price) * abs(t.quantity)  # 1-tick markout of last tick's fills
            lots += abs(t.quantity)
        printed = bool((state.market_trades or {}).get(product)) or lots > 0
        keep = 1.0 - alpha  # discounted Beta-Bernoulli, effective memory 1 / alpha ticks
        st["a"] = keep * st["a"] + (1.0 if printed else 0.0)
        st["b"] = keep * st["b"] + (0.0 if printed else 1.0)
        if lots:
            st["k"] += (1.0 - (1.0 - 1.0 / MARKOUT_MEMORY_LOTS) ** lots) * (mark / lots - st["k"])

    def edge(self, ctx, product, mem):
        st = mem[product]
        rate = st["a"] / (st["a"] + st["b"])
        return max(rate * LOTS_PER_PRINT.get(product, 2.2) * st["k"], 0.0)

    def variance(self, ctx, product, mem):
        return ctx.sigma(product) ** 2


class PinkLean:
    """PINK restores the five-pearl sum: E[20-tick move] = -slope x dev x P(jump within 20 ticks | dev)."""

    name = "pink"
    products = ("PINK_PEARLS",)

    @staticmethod
    def _signal(ctx):
        dev = ctx.glob.get("pd", 0.0)
        hazard = next(h for edge, h in PINK_HAZARD if abs(dev) < edge)
        return dev, hazard

    def target(self, ctx):
        dev, hazard = self._signal(ctx)
        move = -PINK_SLOPE * dev * (1.0 - (1.0 - hazard) ** PINK_HORIZON)
        return move, _clip(move / (2.0 * HALF_SPREAD["PINK_PEARLS"]), -1.0, 1.0)

    def intent(self, ctx, product, mem, q, cap, center=0):
        if "pd" not in ctx.glob:
            return []
        goal = int(round(self.target(ctx)[1] * cap))
        return _take(product, ctx.books[product], ctx.fair[product], q, min(goal, q), max(goal, q))

    def learn(self, ctx, product, mem, alpha):
        return None

    def edge(self, ctx, product, mem):
        dev, hazard = self._signal(ctx)
        return hazard * PINK_SLOPE * abs(dev)

    def variance(self, ctx, product, mem):
        return ctx.sigma(product) ** 2

    def center(self, ctx, cap):
        return int(round(self.target(ctx)[1] * cap))


class ToffeeLean:
    """TOFFEE is OU around a slow anchor: E[move over H] = -dev x (1 - exp(-kappa H)); lean against dev."""

    name = "toffee"
    products = ("TOFFEE_CAKE",)

    def intent(self, ctx, product, mem, q, cap, center=0):
        goal = self.center(ctx, cap)
        return _take(product, ctx.books[product], ctx.fair[product], q, min(goal, q), max(goal, q))

    def learn(self, ctx, product, mem, alpha):
        return None

    def edge(self, ctx, product, mem):
        return TOFFEE_KAPPA * abs(ctx.glob.get("td", 0.0))

    def variance(self, ctx, product, mem):
        return ctx.sigma(product) ** 2

    def center(self, ctx, cap):
        return int(round(_clip(-ctx.glob.get("td", 0.0) / TOFFEE_SD, -1.0, 1.0) * cap))


class Allocator:
    """Splits each product's limit and a portfolio risk budget across (sub-strategy, product) entries.

    allocate(entries) with entries = [(sub_name, product, edge, variance)] returns {(sub_name, product): lots}.
    Risk share w_e by rule; slice Q_e = w_e * B / sigma_e, water-filled so each product's slices sum to at most
    its limit (a product's unused budget goes back to the others). Shares move at most share_step per tick.
    """

    def __init__(self, config, mem):
        self.rule = config["rule"]
        self.budget = float(config["budget"])
        self.share_step = float(config["share_step"])
        self.shares = mem.setdefault("w", {})

    def _scores(self, entries):
        out = {}
        for sub, product, edge, var in entries:
            sigma = SIGMA_EDA[product] if self.rule == "EQ" else math.sqrt(max(var, SIGMA_FLOOR ** 2))
            if self.rule == "EQ":
                score = 1.0
            elif self.rule == "A1":
                score = sigma
            elif self.rule == "A1MR":
                score = sigma / SIGMA_EDA[product] if product in MEAN_REVERTING else 1.0
            elif self.rule == "A3":
                score = 1.0 / sigma
            else:  # A2, fractional Kelly: position mu / sigma^2, so risk share (position x sigma) = mu / sigma
                score = max(edge, 0.0) / sigma
            out[(sub, product)] = (score, sigma)
        return out

    def _water_fill(self, scores, entries):
        products = {}
        for sub, product, _, _ in entries:
            products.setdefault(product, []).append((sub, product))
        caps, free, budget = {}, set(products), self.budget
        for _ in range(len(products)):
            total = sum(scores[k][0] for p in free for k in products[p]) or 1.0
            full = []
            for p in free:
                lots = sum(budget * scores[k][0] / total / scores[k][1] for k in products[p])
                if lots >= LIMITS[p]:
                    full.append(p)
            if not full:
                break
            for p in full:
                keys = products[p]
                lots = {k: budget * scores[k][0] / total / scores[k][1] for k in keys}
                scale = LIMITS[p] / (sum(lots.values()) or 1.0)
                for k in keys:
                    caps[k] = lots[k] * scale
                    budget -= caps[k] * scores[k][1]
                free.discard(p)
            budget = max(budget, 0.0)
        total = sum(scores[k][0] for p in free for k in products[p]) or 1.0
        for p in free:
            for k in products[p]:
                caps[k] = budget * scores[k][0] / total / scores[k][1]
        return caps

    def allocate(self, entries):
        scores = self._scores(entries)
        caps = self._water_fill(scores, entries)
        out = {}
        for key, cap in caps.items():
            sigma = scores[key][1]
            name = key[0] + ":" + key[1]
            want = cap * sigma / self.budget
            prev = self.shares.get(name, want)
            share = prev + _clip(want - prev, -self.share_step, self.share_step)
            self.shares[name] = round(share, 6)
            out[key] = _clip(share * self.budget / sigma, 0.0, float(LIMITS[key[1]]))
        return out


def net_orders(intents):
    """Net a product's intents: aggregate by price, then cancel buys against sells at crossing prices."""
    buys, sells = {}, {}
    for price, qty in intents:
        if qty > 0:
            buys[price] = buys.get(price, 0) + qty
        elif qty < 0:
            sells[price] = sells.get(price, 0) - qty
    for bp in sorted(buys, reverse=True):
        for sp in sorted(sells):
            if sp > bp or buys[bp] == 0:
                break
            cross = min(buys[bp], sells[sp])
            buys[bp] -= cross
            sells[sp] -= cross
    return [(p, v) for p, v in buys.items() if v > 0], [(p, v) for p, v in sells.items() if v > 0]


def clip_to_limit(product, q, buys, sells):
    """Trim the least aggressive orders so q + sum(buys) <= limit and q - sum(sells) >= -limit."""
    limit = LIMITS[product]
    orders, room = [], limit - q
    for price, vol in sorted(buys, reverse=True):
        vol = min(vol, room)
        if vol > 0:
            orders.append(Order(product, int(price), int(vol)))
            room -= vol
    room = limit + q
    for price, vol in sorted(sells):
        vol = min(vol, room)
        if vol > 0:
            orders.append(Order(product, int(price), -int(vol)))
            room -= vol
    return orders


SUBS = (MarketMaker(), PinkLean(), ToffeeLean())
LEANS = {sub.products[0]: sub for sub in SUBS[1:]}


class Trader:
    @staticmethod
    def _load(trader_data):
        if not trader_data:
            return {}
        try:
            data = json.loads(trader_data)
            return data if isinstance(data, dict) else {}
        except (ValueError, TypeError):
            return {}

    def run(self, state: TradingState):
        mem = self._load(state.traderData)
        alpha = _ewma_alpha(CONFIG["half_life"])
        ctx = Context(state, mem, alpha)
        sub_mem = mem.setdefault("u", {})
        entries = []
        for sub in SUBS:
            smem = sub_mem.setdefault(sub.name, {})
            for product in sub.products:
                if product not in ctx.mids:
                    continue
                sub.learn(ctx, product, smem, alpha)
                entries.append((sub.name, product, sub.edge(ctx, product, smem), sub.variance(ctx, product, smem)))
        slices = Allocator(CONFIG, mem).allocate(entries) if entries else {}

        orders = {}
        for product in ctx.mids:
            q = state.position.get(product, 0)
            lean = LEANS.get(product)
            intents = []
            center = 0
            if lean is not None and (lean.name, product) in slices:
                lean_cap = slices[(lean.name, product)]
                center = lean.center(ctx, int(lean_cap))
                intents += lean.intent(ctx, product, sub_mem[lean.name], q, int(lean_cap))
            mm_cap = slices.get(("mm", product), 0.0)
            intents += SUBS[0].intent(ctx, product, sub_mem["mm"], q, mm_cap, center)
            buys, sells = net_orders(intents)
            out = clip_to_limit(product, q, buys, sells)
            if out:
                orders[product] = out
        for st in ctx.stats.values():
            for key in ("m", "d", "g0", "g1", "f"):
                st[key] = round(st[key], 5)
        for smem in sub_mem.values():
            for st in smem.values():
                for key in st:
                    st[key] = round(st[key], 6)
        for key in ("ta", "td", "pt", "pd"):
            if key in ctx.glob:
                ctx.glob[key] = round(ctx.glob[key], 4)
        return orders, 0, json.dumps(mem, separators=(",", ":"))
