"""Generate a single-file orchestrator trader.py from sub-strategy files and a routing table.

    uv run --project ../backtester python tournament/build_orchestrator.py tournament/routes/v1.json --out trader.py

The routing JSON maps each sub-strategy name to its source file and each product to [[sub-strategy, share], ...];
without a gate, shares on one product must sum to at most 1. Products not listed are not traded. Optional keys:
"gate" (risk-gate parameters), "options" (per-strategy overrides) and "priors" (one or more files written by
tournament/estimate_priors.py, giving the gate each pair's offline edge). The output embeds every source
verbatim (each runs in its own module namespace) plus tournament/orchestrator_core.py, so it is self-contained.
"""

import argparse
import json
from pathlib import Path

from quantgen.products import POSITION_LIMITS

ROOT = Path(__file__).resolve().parents[1]
CORE = Path(__file__).with_name("orchestrator_core.py")

HEADER = '''"""QuantiFi 2026 orchestrator.

GENERATED by tournament/build_orchestrator.py from {routes} - do not edit by hand.

Sub-strategies: {subs}.
Routing (product: [sub-strategy, share of the position limit]):
{table}
"""
'''


def validate(config):
    subs, routes = config["subs"], config["routes"]
    for product, slots in routes.items():
        if product not in POSITION_LIMITS:
            raise SystemExit(f"unknown product {product}")
        # Fixed routing splits the limit by share; with the gate on, shares are per-strategy caps and the final
        # clip enforces the limit, so they may sum above 1.
        if config.get("gate") is None and sum(share for _, share in slots) > 1 + 1e-9:
            raise SystemExit(f"{product}: shares sum above 1")
        if any(not 0 <= share <= 1 for _, share in slots):
            raise SystemExit(f"{product}: each share must be in [0, 1]")
        for name, _ in slots:
            if name not in subs:
                raise SystemExit(f"{product}: unknown sub-strategy {name}")


def load_priors(config, routes):
    """{"strategy|product": [mean, var]} for routed pairs, from the file(s) named by the config's "priors" key."""
    files = config.get("priors") or []
    measured = {}
    for name in [files] if isinstance(files, str) else files:
        measured.update(json.loads((ROOT / name).read_text(encoding="utf-8"))["priors"])
    routed = {f"{name}|{product}" for product, slots in routes.items() for name, _ in slots}
    return {key: [round(p["mean"], 6), round(p["var"], 6)] for key, p in sorted(measured.items()) if key in routed}


def render(config, routes_path):
    subs, routes = config["subs"], config["routes"]
    used = sorted({name for slots in routes.values() for name, _ in slots})
    table = "\n".join(f"    {p}: {slots}" for p, slots in sorted(routes.items()))
    parts = [HEADER.format(routes=routes_path.name, subs=", ".join(used), table=table)]
    core = CORE.read_text(encoding="utf-8").split('"""', 2)[2]  # drop the core's own docstring
    parts.append(core.strip() + "\n")
    parts.append("\nSOURCES = {}\n")
    for name in used:
        source = (ROOT / subs[name]).read_text(encoding="utf-8")
        if "'''" in source:
            raise SystemExit(f"{subs[name]} contains ''' and cannot be embedded")
        parts.append(f"\nSOURCES[{name!r}] = r'''{source}'''\n")
    limits = {p: POSITION_LIMITS[p] for p in routes}
    parts.append(f"\nROUTES = {json.dumps(routes, indent=1)}\nLIMITS = {json.dumps(limits, indent=1)}\n")
    parts.append(f"GATE = {config.get('gate')!r}\nOPTIONS = {config.get('options', {})!r}\n")
    parts.append(f"PRIORS = {load_priors(config, routes)!r}\n")
    parts.append(
        "\n\nclass Trader:\n"
        "    def __init__(self):\n"
        "        modules = {name: load_module(name, src) for name, src in SOURCES.items()}\n"
        "        self.orchestrator = Orchestrator(modules, ROUTES, LIMITS, GATE, OPTIONS, PRIORS)\n\n"
        "    def run(self, state):\n"
        "        return self.orchestrator.run(state)\n"
    )
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("routes", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    config = json.loads(args.routes.read_text(encoding="utf-8"))
    validate(config)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(config, args.routes), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
